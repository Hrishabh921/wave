"""
brain/confirm_gate.py — Phase 7, Tier 1 item #1: the reusable
confirm-before-sensitive-action layer.

Before this, the only confirmation flow in Wave was hand-written once for
restart/shutdown (ui/main_window.py's confirm_restart/confirm_shutdown/
_confirm_and_run) - a dialog + a 5-second cancel window, wired up
specifically for those two buttons. That doesn't scale to "every
destructive tool should ask first" without copy-pasting a dialog for each
one, and it only covers the UI's power buttons, not anything the AI (or a
replayed workflow) decides to do on its own.

This module holds the small, stateless pieces of that mechanism - word
lists and pure functions, nothing that needs to remember anything between
calls. The part that DOES need memory (one pending confirmation, with an
expiry) lives on WaveBrain itself as `self.pending_action` (see
brain/groq_core.py's _guard() / _guard_keyword() / _check_pending_confirmation()
/ _replay_confirmed()), since it's inherently per-conversation state, not
something a stateless helper module should own.

How a tool opts in: `@skill(name, description, params, required,
confirm=True)` in groq_core.py - see brain/skills_registry.py. Nothing
else has to change for a brand new sensitive tool to get the same
treatment as the 7 covered in this phase.

Tier 1 item #5: _guard() now decides among three outcomes, not two - see
GuardOutcome and brain/tiers.py/brain/taint.py. "confirm" still works
exactly as the rest of this docstring describes. "deny" is new: for a T3
(destructive) tool when the turn already read something untrusted (see
brain/taint.py), _guard() refuses outright rather than asking, and never
arms self.pending_action - a plain "yes" right afterward replays nothing,
on purpose, since the premise of a deny is that the request may not have
really come from the user in the first place.
"""
import re
from typing import NamedTuple, Optional, Tuple

# ---------------------------------------------------------------------------
# Yes / no recognition - English, Hinglish (romanized), and Hindi
# (Devanagari). Matched against the ENTIRE normalized reply, not a
# substring search - "yes" matches, "yesterday" does not, "yes but also
# open chrome" does not (that's not a plain yes, so it falls through to be
# treated as a brand-new message instead - see _check_pending_confirmation
# in groq_core.py). Keeping this an exact-phrase match is deliberate: a
# confirmation gate that's too eager to read "yes" into an ambiguous reply
# defeats the point of asking in the first place.
# ---------------------------------------------------------------------------
YES_WORDS = frozenset({
    "yes", "yeah", "yep", "yup", "ya", "sure", "confirm", "confirmed",
    "go ahead", "do it", "proceed", "ok", "okay", "k", "fine",
    "haan", "ha", "han", "haanji", "haan ji", "haa", "kar do", "kardo",
    "kar dijiye", "theek hai", "thik hai", "theek h", "chalo",
    "हाँ", "हां", "ठीक है", "कर दो", "कर दीजिए",
})
NO_WORDS = frozenset({
    "no", "nope", "nah", "cancel", "abort", "stop", "don't", "dont",
    "never mind", "nevermind", "negative",
    "nahi", "nahin", "nai", "mat karo", "matt karo", "rehne do",
    "rehne dijiye", "chhodo", "chodo", "cancel karo", "ruko",
    "नहीं", "नही", "मत करो", "रहने दो", "छोड़ो",
})


class GuardOutcome(NamedTuple):
    """What _guard() decides for one tool call. `action` is "run"
    (nothing to show, the caller just proceeds), "confirm" (pending_message
    below, and the caller arms self.pending_action), or "deny" (
    denied_message below, and the caller must NOT arm self.pending_action -
    see the module docstring). `message` is None only for "run"."""
    action: str
    message: Optional[str] = None


def _normalize(text: str) -> str:
    return (text or "").strip().strip(".!?।").strip().lower()


def classify_reply(text: str) -> str:
    """"yes" / "no" / None (anything else - including empty, longer
    sentences, or a reply that doesn't match either list at all)."""
    normalized = _normalize(text)
    if not normalized:
        return None
    if normalized in YES_WORDS:
        return "yes"
    if normalized in NO_WORDS:
        return "no"
    return None


# ---------------------------------------------------------------------------
# Friendly, fixed-template descriptions of what's pending. Fixed templates
# on purpose (same reasoning SARA's guard.py documents for its own spoken
# messages): the confirmation prompt itself has to be something the user
# can trust, so its wording is never generated by the LLM or built from
# anything an untrusted source could shape beyond the plain argument
# values Wave is about to act on.
# ---------------------------------------------------------------------------
def _truncate(value: str, n: int = 80) -> str:
    value = str(value or "").strip()
    return value if len(value) <= n else value[: n - 1] + "…"


_FRIENDLY_ACTIONS = {
    "delete_file": lambda a: f"delete the file '{_truncate(a.get('file_name'))}'",
    "delete_latest_screenshot": lambda a: "delete your most recently taken screenshot",
    "forget_memory": lambda a: f"forget what I know about '{_truncate(a.get('key'))}'",
    "send_whatsapp_message": lambda a: (
        f"send a WhatsApp message to {_truncate(a.get('contact_name'))} saying "
        f"\"{_truncate(a.get('message'))}\""
    ),
    "close_app": lambda a: f"close {_truncate(a.get('app_name'))}",
    "create_file": lambda a: f"create a file named '{_truncate(a.get('file_name'))}'",
    "take_photo": lambda a: "take a photo with your webcam",
}


def describe_action(tool_name: str, args: dict) -> str:
    """Short, human phrase for what a gated tool call is about to do - the
    middle of 'Before I {describe_action(...)}, ...'. Any tool not in the
    hand-written table above (a future confirm=True tool, or one from a
    hot-loaded user skill) still gets a sane generic fallback instead of
    this ever raising or returning something blank."""
    builder = _FRIENDLY_ACTIONS.get(tool_name)
    if builder:
        try:
            described = builder(args or {})
            if described:
                return described
        except Exception:
            pass
    return tool_name.replace("_", " ").strip() or "do that"


def pending_message(tool_name: str, args: dict) -> str:
    """The result _guard()/_guard_keyword() hand back instead of running
    the tool. On the AI tool-calling path this becomes a tool-result
    message the model paraphrases for the user (see groq_core.py's
    TOOL_RESULT_GUIDANCE); on the keyword path it's shown to the user
    as-is - written to stand on its own either way."""
    action = describe_action(tool_name, args)
    return (
        f"Before I {action}, I need you to confirm — reply 'yes' to go ahead or "
        f"'no' to cancel. (This request expires if I don't hear back shortly.)"
    )


def _source_phrase(sources: Tuple[str, ...]) -> str:
    """" I read" / " from a web search" / " from a web search and an
    attached file (notes.txt)" - built to drop straight into "...something{
    this} earlier in this conversation...". English-only, same as the rest
    of this module's output text (groq_core.py's model-paraphrase layer,
    not this module, is where any translation for the user happens - see
    pending_message() above)."""
    sources = tuple(sources or ())
    if not sources:
        return " I read"
    if len(sources) == 1:
        return f" from {sources[0]}"
    return f" from {', '.join(sources[:-1])} and {sources[-1]}"


def denied_message(tool_name: str, args: dict, sources: Tuple[str, ...] = ()) -> str:
    """The result _guard() hands back for a "deny" GuardOutcome - Tier 1
    item #5. Only reached for a T3 tool when the turn already read
    something untrusted (brain/taint.py), so unlike pending_message()
    this never asks a yes/no question: nothing here can be approved with
    a plain "yes", on purpose (see this module's docstring)."""
    action = describe_action(tool_name, args)
    where = _source_phrase(sources)
    return (
        f"I won't {action} right now — something{where} earlier in this "
        f"conversation could be behind that, and this one's too sensitive to "
        f"run on the strength of that alone. If you genuinely want this, ask "
        f"me again yourself, in your own words."
    )
